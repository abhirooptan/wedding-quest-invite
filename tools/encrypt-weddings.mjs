// Encrypts the private per-wedding details into a public, opaque JS file.
// Usage (from A:/Claude/Invitation):
//   node deploy/tools/encrypt-weddings.mjs private/weddings.json deploy/locale/weddings.enc.js
//
// Each wedding's payload is AES-GCM encrypted with a key derived (PBKDF2) from
// its password, so the published page holds no readable details or passwords.
// The browser derives one key from what the guest typed and tries every item;
// only the matching one authenticates. Keep this in sync with unlockWedding()
// in index.html (normalisation, iterations, salt/iv layout).
import { readFileSync, writeFileSync } from 'node:fs';
import { webcrypto as crypto } from 'node:crypto';
import { pathToFileURL } from 'node:url';

const ITERATIONS = 250000;
const [src, out] = process.argv.slice(2);
if (!src || !out) { console.error('usage: encrypt-weddings.mjs <weddings.json> <out.js>'); process.exit(1); }

const normalise = (pw) => pw.normalize('NFC').trim().toLowerCase();
const b64 = (buf) => Buffer.from(buf).toString('base64');

const { weddings } = JSON.parse(readFileSync(src, 'utf8'));
const seen = new Set();
for (const w of weddings) {
  if (!w.password || w.password.startsWith('CHANGE-ME')) console.warn(`WARNING: "${w.id}" still has a placeholder password`);
  const pw = normalise(w.password);
  if (seen.has(pw)) { console.error(`duplicate password for "${w.id}"`); process.exit(1); }
  seen.add(pw);
}

const salt = crypto.getRandomValues(new Uint8Array(16));
async function keyFor(pw) {
  const base = await crypto.subtle.importKey('raw', new TextEncoder().encode(normalise(pw)), 'PBKDF2', false, ['deriveKey']);
  return crypto.subtle.deriveKey({ name: 'PBKDF2', salt, iterations: ITERATIONS, hash: 'SHA-256' },
    base, { name: 'AES-GCM', length: 256 }, false, ['encrypt']);
}

const items = [];
for (const w of weddings) {
  const { password, heroSvgFile, ...payload } = w;
  // venue line-drawing is inlined into the encrypted payload so the
  // published site doesn't reveal either venue to the other wedding's guests
  if (heroSvgFile) payload.heroSvg = readFileSync(new URL(heroSvgFile, pathToFileURL(src)), 'utf8');
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ct = await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, await keyFor(password),
    new TextEncoder().encode(JSON.stringify(payload)));
  items.push({ iv: b64(iv), ct: b64(ct) });
}
items.sort(() => Math.random() - 0.5); // order shouldn't hint which blob is which

writeFileSync(out,
  '// GENERATED by tools/encrypt-weddings.mjs -- do not edit by hand.\n' +
  'window.WEDDINGS_ENC = ' + JSON.stringify({ iterations: ITERATIONS, salt: b64(salt), items }) + ';\n');
console.log(`wrote ${items.length} encrypted weddings to ${out}`);
